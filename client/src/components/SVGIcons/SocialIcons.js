// Function to get icon name from URL or service name
export const getIconNameFromUrl = (url) => {
  if (!url) return null;
  
  const lowercaseUrl = url.toLowerCase();
  
  // Check for specific domains
  if (lowercaseUrl.includes('linkedin.com')) return 'linkedin';
  if (lowercaseUrl.includes('twitter.com') || lowercaseUrl.includes('x.com')) return 'twitter';
  if (lowercaseUrl.includes('youtube.com')) return 'youtube';
  if (lowercaseUrl.includes('facebook.com')) return 'facebook';
  if (lowercaseUrl.includes('instagram.com')) return 'instagram';
  if (lowercaseUrl.includes('github.com')) return 'github';
  if (lowercaseUrl.includes('scholar.google')) return 'googleScholar';
  if (lowercaseUrl.includes('orcid.org')) return 'orcid';
  if (lowercaseUrl.includes('researchgate.net')) return 'researchGate';
  if (lowercaseUrl.includes('scopus.com')) return 'scopus';
  if (lowercaseUrl.includes('ieee.org')) return 'ieee';
  if (lowercaseUrl.includes('academia.edu')) return 'academia';
  if (lowercaseUrl.includes('mendeley.com')) return 'mendeley';
  if (lowercaseUrl.includes('publons.com') || lowercaseUrl.includes('webofscience.com')) return 'publons';
  if (lowercaseUrl.includes('mailto:')) return 'email';
  if (lowercaseUrl.includes('tel:')) return 'phone';
  
  // Default to website icon for other URLs
  return 'website';
};

